# Chapter 3: One Sentence


def introduce_banji():
    # Banji follows Sir Git out of the monitor.
    print(
        "A kid in a red bandana tumbled out of the monitor behind Sir Git, "
        "landing on the keyboard."
    )
    print('\"This is Banji,\" Sir Git said, helping him up.')
    print()

    print('Banji glanced at the letters he had accidentally typed. "My mistake."')
    print()

    # The grandmother's watch gives Banji an idea to help the writer.
    print(
        "Banji noticed the watch in the writer's hand. "
        '\"Who gave you that?\"'
    )
    print('\"My grandmother. She used to read all my stories.\"')
    print('\"What was she like?\"')
    print('The writer smiled faintly. \"She always read the last page first.\"')
    print('Banji grinned. \"That sounds like a good first sentence.\"')
    print('"You think so?" the writer asked.')
    print('"Sure. Now I want to know what else she did."')
    print()
    print("The writer set down the watch and began to type.")
    print("Sir Git and Banji sat quietly beside the screen as the first line appeared.")


if __name__ == "__main__":
    introduce_banji()
